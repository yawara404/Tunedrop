const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('frontend/app.js', 'utf8');
const start = source.indexOf('export function spreadLegacyRadarMap');
const end = source.indexOf('export async function loadRadarData', start);
const ctx = vm.createContext({});
vm.runInContext(source.slice(start, end).replace('export ', ''), ctx);
const spread = ctx.spreadLegacyRadarMap;
const make = coords => ({points: coords.map(([x,y],i) => ({youtube_id:String(i), features:{x,y,tempo:120}}))});
const wide = make([[.1,.2],[.101,.201],[.105,.202],[.9,.8]]);
assert.equal(JSON.stringify(spread(wide).points), JSON.stringify(wide.points));
const input = make([[.4,.4],[.401,.401],[.43,.42],[.5,.5]]);
const snapshot = JSON.stringify(input);
const result = spread(input);
assert.equal(JSON.stringify(input),snapshot);
assert.equal(result.layout_version,3);
assert.equal(spread(result),result);
assert.equal(JSON.stringify(spread(input)),JSON.stringify(result));
const distance = (p,a,b) => Math.hypot(p[a].features.x-p[b].features.x,p[a].features.y-p[b].features.y);
const scale = distance(result.points,0,1)/distance(input.points,0,1);
for(let i=0;i<4;i++) for(let j=0;j<i;j++) assert(Math.abs(distance(result.points,i,j)-distance(input.points,i,j)*scale)<1e-10);
assert(result.points.every(p => p.features.tempo===120));
assert.equal(spread({points:[]}).points.length,0);
console.log('PASS: natural spacing, global scaling only, no double correction, data preserved');
